_FILTERS_SECTION = """\
#### Filters

Filters can be specified as structured rules or raw rsync filter strings, mixed freely:

```yaml
filters:
  # Structured include/exclude rules
  - include: "*.jpg"          # becomes "+ *.jpg"
  - exclude: "*.tmp"          # becomes "- *.tmp"

  # Merge: read rules from an external file (applied globally)
  - merge: /etc/nbkp/extra-rules.txt
  - merge: ~/my-rules.txt    # tilde is expanded

  # Dir-merge: per-directory filter files (rsync discovers them as it walks the tree)
  - dir-merge: .rsync-filter

  # Dir-merge with exclude-self: equivalent to rsync's -FF
  # (use per-directory filters, but don't transfer the filter files themselves)
  - dir-merge:
      path: .rsync-filter
      exclude-self: true

  # Raw rsync filter strings (for advanced modifiers like ,e or ,n)
  - "H .git"                  # hide .git from transfer
  - "- __pycache__/"          # exclude __pycache__
  - "dir-merge,e /.rsync-filter"  # dir-merge with word-splitting
```

**`merge`** reads a file of filter rules once and applies them at the point where they
appear in the list. Tilde (`~`) is expanded in merge paths. This is similar to
`filter-file`, but `filter-file` is always appended after all inline filters, while
`merge` respects its position in the list.

**`dir-merge`** tells rsync to look for the named file in each directory as it walks the
source tree. Rules from each file apply only to that directory and its subdirectories.
The `exclude-self` option appends a `- <filename>` rule to prevent the filter files from
being transferred (equivalent to rsync's `-FF` flag). Dir-merge paths are not
tilde-expanded (they are relative filenames resolved by rsync per-directory).

Each structured rule is a mapping with exactly one key: `{include: "*.jpg", exclude:
"*"}` is rejected rather than read as one of its rules. Write two list items instead.

Filters are applied in order as `--filter=RULE` arguments. When `filter-file` is also
set, inline filters are applied first."""


# Fields auto-injected by validators, not part of the user-facing config
_HIDDEN_FIELDS = {"slug"}

# Discriminator fields that should show as **required** with a description
_DISCRIMINATOR_OVERRIDES: dict[str, tuple[str, str]] = {
    "type": ("**required**", "Volume type discriminator"),
}


def _to_kebab(name: str) -> str:
    return name.replace("_", "-")


def _constraints_str(info: FieldInfo) -> str:
    """Extract constraint annotations (ge, le) from field metadata."""
    constraints: list[str] = []
    if info.metadata:
        for m in info.metadata:
            if hasattr(m, "ge") and m.ge is not None:
                constraints.append(f">= {m.ge}")
            if hasattr(m, "le") and m.le is not None:
                constraints.append(f"<= {m.le}")
    return f" ({', '.join(constraints)})" if constraints else ""


# Plain bool and a TypeIs to a known type: an inline isinstance() check would
# narrow the value to list[Unknown] or type[Unknown], which strict pyright
# rejects wherever the value is used next.
def _is_empty_list(value: object) -> bool:
    return isinstance(value, list) and not value


def _is_model_class(annotation: object) -> TypeIs[type[BaseModel]]:
    return isinstance(annotation, type) and issubclass(annotation, BaseModel)


def _type_str(info: FieldInfo) -> str:
    annotation = info.annotation
    if annotation is None:
        return "any"

    origin = get_origin(annotation)
    args = get_args(annotation)

    if origin is Annotated:
        inner_info = FieldInfo(annotation=args[0])
        inner_info.metadata = info.metadata
        return _type_str(inner_info)

    # X | None → show the inner type with original constraints. Since 3.14,
    # typing.Union is types.UnionType, so this also covers Optional[X] and Union[...].
    if origin is UnionType:
        non_none = [a for a in args if a is not type(None)]
        if len(non_none) == 1:
            # Pass original info to preserve constraints
            inner_info = FieldInfo(annotation=non_none[0])
            inner_info.metadata = info.metadata
            return _type_str(inner_info)

    if origin is Literal:
        return " \\| ".join(f'`"{a}"`' for a in args)

    if origin is list:
        if args:
            inner_info = FieldInfo(annotation=args[0])
            return f"list of {_type_str(inner_info)}s"
        return "list"

    if origin is dict:
        return "object"

    if _is_model_class(annotation):
        return "object"

    type_map: dict[object, str] = {
        str: "string",
        int: "integer",
        float: "float",
        bool: "boolean",
    }
    if annotation in type_map:
        return type_map[annotation] + _constraints_str(info)

    return str(annotation)


def _default_str(info: FieldInfo) -> str:
    if info.is_required():
        return "**required**"

    default = info.default
    if default is None:
        return "`null`"
    if isinstance(default, bool):
        return f"`{str(default).lower()}`"
    if isinstance(default, (int, float)):
        return f"`{default}`"
    if isinstance(default, str):
        return f'`"{default}"`'
    if _is_empty_list(default):
        return "`[]`"

    if info.default_factory is not None:
        factory_result = info.get_default(call_default_factory=True)
        if isinstance(factory_result, BaseModel):
            return "see below"
        if _is_empty_list(factory_result):
            return "`[]`"
        return str(factory_result)

    return str(default)


def table_cell(text: str) -> str:
    r"""
    Escape `|` so free text cannot split a Markdown table cell.

    GitHub splits a row on every unescaped `|`, inside a code span too, and
    renders `\|` as `|` in both.
    """
    return text.replace("|", "\\|")


def _generate_table(model: type[BaseModel]) -> str:
    """Generate a markdown table from a Pydantic model's fields."""
    rows = ["| Field | Type | Default | Description |", "|---|---|---|---|"]
    for name, info in model.model_fields.items():
        if name in _HIDDEN_FIELDS:
            continue
        field_name = f"`{_to_kebab(name)}`"
        if name in _DISCRIMINATOR_OVERRIDES:
            override_default, override_desc = _DISCRIMINATOR_OVERRIDES[name]
            field_type = _type_str(info)
            rows.append(
                f"| {field_name} | {field_type} | {override_default}"
                f" | {table_cell(override_desc)} |",
            )
        else:
            field_type = _type_str(info)
            field_default = _default_str(info)
            field_desc = table_cell(info.description or "")
            rows.append(
                f"| {field_name} | {field_type} | {field_default} | {field_desc} |",
            )
    return "\n".join(rows)


def _generate_sections() -> dict[str, str]:
    """Generate all marker-delimited sections as a dict of {name: body}."""
    sections: dict[str, str] = {}

    sections["CONFIGREF:TOP_LEVEL"] = f"{_TOP_LEVEL_STRUCTURE}\n"

    sections["CONFIGREF:SSH_ENDPOINTS"] = "\n".join(
        [
            "#### `ssh-endpoints.<slug>` — SSH Endpoint",
            "",
            _generate_table(SshEndpoint),
            "",
            _SSH_ENDPOINT_NOTES,
            "",
            "---",
            "",
            "#### `connection-options` — SSH Connection Options",
            "",
            _generate_table(SshConnectionOptions),
            "",
        ],
    )

    sections["CONFIGREF:VOLUMES"] = "\n".join(
        [
            "#### `volumes.<slug>` — Local Volume",
            "",
            _generate_table(LocalVolume),
            "",
            _LOCAL_VOLUME_NOTES,
            "",
            "#### `volumes.<slug>` — Remote Volume",
            "",
            _generate_table(RemoteVolume),
            "",
            "---",
            "",
            "#### `mount` — Mount Config",
            "",
            _generate_table(MountConfig),
            "",
            _MOUNT_CONFIG_NOTES,
            "",
            "#### `encryption` — LUKS Encryption Config",
            "",
            _generate_table(LuksEncryptionConfig),
            "",
            _LUKS_ENCRYPTION_NOTES,
            "",
            "---",
            "",
            _CREDENTIAL_PROVIDER_NOTES,
            "",
        ],
    )

    sections["CONFIGREF:SYNC_ENDPOINTS"] = "\n".join(
        [
            "#### `sync-endpoints.<slug>` — Sync Endpoint",
            "",
            _generate_table(SyncEndpoint),
            "",
            _SYNC_ENDPOINT_NOTES,
            "",
            "---",
            "",
            "#### `btrfs-snapshots` / `hard-link-snapshots`",
            "",
            _generate_table(BtrfsSnapshotConfig),
            "",
        ],
    )

    sections["CONFIGREF:SYNCS"] = "\n".join(
        [
            "#### `syncs.<slug>` — Sync Config",
            "",
            _generate_table(SyncConfig),
            "",
            _SYNC_CONFIG_NOTES,
            "",
            "---",
            "",
            "#### `rsync-options` — Rsync Options",
            "",
            _generate_table(RsyncOptions),
            "",
            _RSYNC_OPTIONS_NOTES,
            "",
            "---",
            "",
            _FILTERS_SECTION,
            "",
        ],
    )

    return sections


app = typer.Typer(add_completion=False)


@app.command()
def main(
    *,
    check: Annotated[
        bool,
        typer.Option(
            "--check",
            help="Check that docs are up to date (exit non-zero if not)",
        ),
    ] = False,
) -> None:
    """Generate or check config reference tables in config-reference.md."""
    sections = _generate_sections()
    current = (
        CONFIG_REFERENCE_MD.read_text(encoding="utf-8")
        if CONFIG_REFERENCE_MD.exists()
        else ""
    )
    expected = current
    for name, body in sections.items():
        expected = splice_section(expected, name, body)

    if check:
        if current == expected:
            _stdout.print(
                "Config reference in config-reference.md is up to date.",
                markup=False,
            )
        else:
            _stderr.print(
                f"Config reference in {CONFIG_REFERENCE_MD} is out of date.\n"
                "Run `mise run configdocs` to regenerate.",
                markup=False,
            )
            sys.exit(1)
    else:
        CONFIG_REFERENCE_MD.write_text(expected, encoding="utf-8")
        _stdout.print(
            f"Updated config reference in {CONFIG_REFERENCE_MD}",
            markup=False,
        )


if __name__ == "__main__":
    app()
