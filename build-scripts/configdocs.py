"""
Auto-generate configuration reference tables into docs/config-reference.md.

Introspects the config protocol models and splices field tables into
docs/config-reference.md between marker comments. Use --check to verify the
docs are up to date.

Usage:
    python build-scripts/configdocs.py          # regenerate the tables in the doc
    python build-scripts/configdocs.py --check  # exit non-zero if out of date

Why hand-rolled instead of a library?
    Existing Pydantic doc-gen tools (docdantic, mdantic, settings-doc,
    pydantic-settings-export) are MkDocs/Sphinx plugins designed to run inside
    a documentation build pipeline. They can't be invoked as a standalone
    function to produce a .md file with a --check mode. Our requirements
    (kebab-case aliases, hidden fields, discriminator overrides, interleaved
    prose sections) are too specific for any of them. The introspection code
    is ~120 lines and unlikely to need changes unless the model structure
    fundamentally changes.
"""

import builtins
import sys
import types
import typing
from pathlib import Path
from typing import Annotated, Any, TypeIs, get_args, get_origin

import typer
from pydantic import BaseModel
from pydantic.fields import FieldInfo
from rich.console import Console

from nbkp.config.protocol.ssh_endpoint import SshConnectionOptions, SshEndpoint
from nbkp.config.protocol.sync import RsyncOptions, SyncConfig
from nbkp.config.protocol.sync_endpoint import BtrfsSnapshotConfig, SyncEndpoint
from nbkp.config.protocol.volume import (
    LocalVolume,
    LuksEncryptionConfig,
    MountConfig,
    RemoteVolume,
)

CONFIG_REFERENCE_MD = Path("docs/config-reference.md")

_stdout = Console(soft_wrap=True, highlight=False)
_stderr = Console(stderr=True, soft_wrap=True, highlight=False)


def _begin_marker(name: str) -> str:
    return (
        f"<!-- BEGIN {name} (auto-generated by: mise run configdocs"
        " — do not edit manually) -->"
    )


def _end_marker(name: str) -> str:
    return f"<!-- END {name} -->"


def _marker_problem(file_content: str, begin: str, end: str) -> str | None:
    """Say what is wrong with a section's markers, or None when they are usable."""
    match (file_content.count(begin), file_content.count(end)):
        case (0, _) | (_, 0):
            return "not found"
        case (1, 1):
            return (
                "out of order (END before BEGIN)"
                if file_content.find(end) < file_content.find(begin)
                else None
            )
        case _:
            return "repeated"


def splice_section(file_content: str, name: str, body: str) -> str:
    """
    Replace content between BEGIN/END markers for the given section name.

    Exits when either marker is missing or repeated, or END comes before BEGIN:
    splicing would then rewrite the wrong span of the file without a word.
    """
    begin = _begin_marker(name)
    end = _end_marker(name)
    problem = _marker_problem(file_content, begin, end)
    if problem is not None:
        _stderr.print(
            f"Error: markers for {name} {problem} in {CONFIG_REFERENCE_MD}.\n"
            f"Expected, once each and in this order:\n  {begin}\n  {end}",
            markup=False,
        )
        sys.exit(1)
    begin_idx = file_content.find(begin)
    end_idx = file_content.find(end)
    return (
        file_content[:begin_idx]
        + begin
        + "\n"
        + body
        + end
        + file_content[end_idx + len(end) :]
    )


_TOP_LEVEL_STRUCTURE = """\
```yaml
ssh-endpoints:
  <slug>: <SshEndpoint>

volumes:
  <slug>: <LocalVolume | RemoteVolume>

sync-endpoints:
  <slug>: <SyncEndpoint>

syncs:
  <slug>: <SyncConfig>
```

Slugs must be lowercase alphanumeric with hyphens (e.g. `my-nas`, `usb-drive`). Max 50
characters."""

_SSH_ENDPOINT_NOTES = (
    "Fields not explicitly set (`port`, `user`, `key`) are automatically filled from"
    " `~/.ssh/config`."
)

_LOCAL_VOLUME_NOTES = (
    "> **YAML caveat:** Bare `~` is interpreted as `null` by YAML. Always quote it:"
    ' `path: "~"` or `path: "~/subdir"`.'
)

_MOUNT_CONFIG_NOTES = """\
The `mount` section is optional on both local and remote volumes. When present, nbkp
manages the mount/umount lifecycle automatically during `run`.

For encrypted volumes, `device-uuid` is the LUKS container UUID (from `crypttab` or
`blkid`). For unencrypted volumes, it is the filesystem UUID (from `fstab` or
`blkid`)."""

_LUKS_ENCRYPTION_NOTES = """\
The `type: luks` field is a discriminator for future encryption backend extensibility.
Currently only LUKS is supported.

The `passphrase-id` is used as a lookup key with the configured `credential-provider`.
Multiple volumes can share the same `passphrase-id` — the passphrase is cached in memory
during a single run."""

_CREDENTIAL_PROVIDER_NOTES = """\
Top-level config fields for credential retrieval:

| Field | Type | Default | Description |
|---|---|---|---|
| `credential-provider` | `"keyring"` \\| `"prompt"` \\| `"env"` \\| `"command"` | `"keyring"` | How LUKS passphrases are retrieved |
| `credential-command` | list of strings | `null` | Command template for `command` provider. Must contain `{id}` placeholder (e.g. `["pass", "show", "nbkp/{id}"]`). A leading `~` in the program (the first item) is expanded |

Providers:
- **keyring**: `keyring.get_password("nbkp", passphrase_id)` — uses macOS Keychain or
  Linux SecretService. Requires `uv tool install 'nbkp[keyring]'`.
- **prompt**: interactive hidden input prompt.
- **env**: reads `NBKP_PASSPHRASE_<ID>`: the passphrase-id uppercased, with every
  character other than a letter or digit replaced by `_` (`nas.disk-1` →
  `NBKP_PASSPHRASE_NAS_DISK_1`). Two passphrase-ids that map to the same variable
  (`usb-drive` and `usb_drive`) are rejected when the config loads.
- **command**: runs command template with `{id}` replaced by passphrase-id. The first
  line of its output, without the line break, is the passphrase (the `pass` convention:
  later lines hold metadata); spaces are kept."""  # noqa: E501 -- a Markdown table row cannot wrap

_SYNC_ENDPOINT_NOTES = """\
Only one of `btrfs-snapshots` and `hard-link-snapshots` can be enabled per endpoint.
Each (volume, subdir) pair must be unique across all sync endpoints.

When used as a **source**, enabling snapshots tells rsync to read from the `latest/`
directory instead of the volume root. When used as a **destination**, enabling snapshots
activates snapshot creation after each successful sync."""

_SYNC_CONFIG_NOTES = (
    "Each destination endpoint can only be used by one sync (no two syncs may share"
    " the same destination)."
)

_RSYNC_OPTIONS_NOTES = """\
Default rsync flags (when `default-options-override` is not set):

```
-a --delete --delete-excluded --partial-dir=.rsync-partial --safe-links
```

The sentinel filters `--filter=H .nbkp-*` and `--filter=P .nbkp-*` follow them
in every sync, with or without `default-options-override`: they keep rsync from
copying the source's sentinels or deleting the destination's."""

_FILTERS_SECTION = """\
#### Filters

Filters can be specified as structured rules or raw rsync filter strings, mixed freely:

```yaml
filters:
  # Structured include/exclude rules
  - include: "*.jpg"          # becomes "+ *.jpg"
  - exclude: "*.tmp"          # becomes "- *.tmp"

  # Merge: read rules from an external file (applied globally)
  - merge: /etc/nbkp/extra-rules.txt
  - merge: ~/my-rules.txt    # tilde is expanded

  # Dir-merge: per-directory filter files (rsync discovers them as it walks the tree)
  - dir-merge: .rsync-filter

  # Dir-merge with exclude-self: equivalent to rsync's -FF
  # (use per-directory filters, but don't transfer the filter files themselves)
  - dir-merge:
      path: .rsync-filter
      exclude-self: true

  # Raw rsync filter strings (for advanced modifiers like ,e or ,n)
  - "H .git"                  # hide .git from transfer
  - "- __pycache__/"          # exclude __pycache__
  - "dir-merge,e /.rsync-filter"  # dir-merge with word-splitting
```

**`merge`** reads a file of filter rules once and applies them at the point where they
appear in the list. Tilde (`~`) is expanded in merge paths. This is similar to
`filter-file`, but `filter-file` is always appended after all inline filters, while
`merge` respects its position in the list.

**`dir-merge`** tells rsync to look for the named file in each directory as it walks the
source tree. Rules from each file apply only to that directory and its subdirectories.
The `exclude-self` option appends a `- <filename>` rule to prevent the filter files from
being transferred (equivalent to rsync's `-FF` flag). Dir-merge paths are not
tilde-expanded (they are relative filenames resolved by rsync per-directory).

Each structured rule is a mapping with exactly one key: `{include: "*.jpg", exclude:
"*"}` is rejected rather than read as one of its rules. Write two list items instead.

Filters are applied in order as `--filter=RULE` arguments. When `filter-file` is also
set, inline filters are applied first."""


# Fields auto-injected by validators, not part of the user-facing config
_HIDDEN_FIELDS = {"slug"}

# The volume union's discriminator: required in the YAML although each model
# gives it a default, since pydantic picks the model from it. Keyed by model as
# well as field, so another model's `type` (the encryption backend) keeps its
# own default and description.
_VOLUME_DISCRIMINATOR = ("**required**", "Volume type discriminator")
_DISCRIMINATOR_OVERRIDES: dict[tuple[type[BaseModel], str], tuple[str, str]] = {
    (LocalVolume, "type"): _VOLUME_DISCRIMINATOR,
    (RemoteVolume, "type"): _VOLUME_DISCRIMINATOR,
}


def _constraints_str(info: FieldInfo) -> str:
    """Extract constraint annotations (ge, le) from field metadata."""
    constraints = [
        f"{operator} {bound}"
        for m in info.metadata
        for operator, bound in (
            (">=", getattr(m, "ge", None)),
            ("<=", getattr(m, "le", None)),
        )
        if bound is not None
    ]
    return f" ({', '.join(constraints)})" if constraints else ""


# Plain bool and a TypeIs to a known type: an inline isinstance() check would
# narrow the value to list[Unknown] or type[Unknown], which strict pyright
# rejects wherever the value is used next.
def _is_empty_list(value: object) -> bool:
    return isinstance(value, list) and not value


def _is_model_class(annotation: object) -> TypeIs[type[BaseModel]]:
    return isinstance(annotation, type) and issubclass(annotation, BaseModel)


_SCALAR_TYPES: dict[object, str] = {
    str: "string",
    int: "integer",
    float: "float",
    bool: "boolean",
}


def _keeping_constraints(info: FieldInfo, annotation: type[Any] | None) -> FieldInfo:
    """Return *info* narrowed to *annotation*, with its constraints kept."""
    inner = FieldInfo(annotation=annotation)
    inner.metadata = info.metadata
    return inner


def _type_str(info: FieldInfo) -> str:
    annotation = info.annotation
    args = get_args(annotation)
    # Since 3.14, typing.Union is types.UnionType, so X | None also covers
    # Optional[X] and Union[...]: it shows as X, with X's constraints.
    non_none = [a for a in args if a is not type(None)]
    match (annotation, get_origin(annotation)):
        case (None, _):
            return "any"
        case (_, typing.Annotated):
            return _type_str(_keeping_constraints(info, args[0]))
        case (_, types.UnionType) if len(non_none) == 1:
            return _type_str(_keeping_constraints(info, non_none[0]))
        case (_, typing.Literal):
            return " \\| ".join(f'`"{a}"`' for a in args)
        case (_, builtins.list):
            return (
                f"list of {_type_str(FieldInfo(annotation=args[0]))}s"
                if args
                else "list"
            )
        case (_, builtins.dict):
            return "object"
        case _ if _is_model_class(annotation):
            return "object"
        case _ if annotation in _SCALAR_TYPES:
            return _SCALAR_TYPES[annotation] + _constraints_str(info)
        case _:
            return str(annotation)


def _factory_default_str(info: FieldInfo) -> str:
    factory_result = info.get_default(call_default_factory=True)
    match factory_result:
        case BaseModel():
            return "see below"
        case _ if _is_empty_list(factory_result):
            return "`[]`"
        case _:
            return str(factory_result)


def _default_str(info: FieldInfo) -> str:
    default = info.default
    # bool before int: a bool is an int, and renders as true/false.
    match default:
        case _ if info.is_required():
            return "**required**"
        case None:
            return "`null`"
        case bool():
            return f"`{str(default).lower()}`"
        case int() | float():
            return f"`{default}`"
        case str():
            return f'`"{default}"`'
        case _ if _is_empty_list(default):
            return "`[]`"
        case _ if info.default_factory is not None:
            return _factory_default_str(info)
        case _:
            return str(default)


def table_cell(text: str) -> str:
    r"""
    Escape `|` so free text cannot split a Markdown table cell.

    GitHub splits a row on every unescaped `|`, inside a code span too, and
    renders `\|` as `|` in both.
    """
    return text.replace("|", "\\|")


def _table_row(model: type[BaseModel], name: str, info: FieldInfo) -> str:
    """Return the row documenting *model*'s field *name*, under its config key."""
    default, description = _DISCRIMINATOR_OVERRIDES.get((model, name)) or (
        _default_str(info),
        info.description or "",
    )
    return (
        f"| `{info.alias or name}` | {_type_str(info)} | {default}"
        f" | {table_cell(description)} |"
    )


def generate_table(model: type[BaseModel]) -> str:
    """Generate a markdown table from a Pydantic model's fields."""
    return "\n".join(
        [
            "| Field | Type | Default | Description |",
            "|---|---|---|---|",
            *(
                _table_row(model, name, info)
                for name, info in model.model_fields.items()
                if name not in _HIDDEN_FIELDS
            ),
        ],
    )


def _blocks(*parts: str) -> str:
    """Join Markdown blocks with a blank line between each."""
    return "\n\n".join(parts)


def _section(*parts: str) -> str:
    """Return a marker-delimited section's body: its blocks, ending with a newline."""
    return _blocks(*parts) + "\n"


def _table_section(heading: str, model: type[BaseModel], *notes: str) -> str:
    return _blocks(f"#### {heading}", generate_table(model), *notes)


def _ssh_endpoints_section() -> str:
    return _section(
        _table_section(
            "`ssh-endpoints.<slug>` — SSH Endpoint",
            SshEndpoint,
            _SSH_ENDPOINT_NOTES,
        ),
        "---",
        _table_section(
            "`connection-options` — SSH Connection Options",
            SshConnectionOptions,
        ),
    )


def _volumes_section() -> str:
    return _section(
        _table_section(
            "`volumes.<slug>` — Local Volume",
            LocalVolume,
            _LOCAL_VOLUME_NOTES,
        ),
        _table_section("`volumes.<slug>` — Remote Volume", RemoteVolume),
        "---",
        _table_section("`mount` — Mount Config", MountConfig, _MOUNT_CONFIG_NOTES),
        _table_section(
            "`encryption` — LUKS Encryption Config",
            LuksEncryptionConfig,
            _LUKS_ENCRYPTION_NOTES,
        ),
        "---",
        _CREDENTIAL_PROVIDER_NOTES,
    )


def _sync_endpoints_section() -> str:
    return _section(
        _table_section(
            "`sync-endpoints.<slug>` — Sync Endpoint",
            SyncEndpoint,
            _SYNC_ENDPOINT_NOTES,
        ),
        "---",
        _table_section(
            "`btrfs-snapshots` / `hard-link-snapshots`",
            BtrfsSnapshotConfig,
        ),
    )


def _syncs_section() -> str:
    return _section(
        _table_section("`syncs.<slug>` — Sync Config", SyncConfig, _SYNC_CONFIG_NOTES),
        "---",
        _table_section(
            "`rsync-options` — Rsync Options",
            RsyncOptions,
            _RSYNC_OPTIONS_NOTES,
        ),
        "---",
        _FILTERS_SECTION,
    )


def _generate_sections() -> dict[str, str]:
    """Generate all marker-delimited sections as a dict of {name: body}."""
    return {
        "CONFIGREF:TOP_LEVEL": f"{_TOP_LEVEL_STRUCTURE}\n",
        "CONFIGREF:SSH_ENDPOINTS": _ssh_endpoints_section(),
        "CONFIGREF:VOLUMES": _volumes_section(),
        "CONFIGREF:SYNC_ENDPOINTS": _sync_endpoints_section(),
        "CONFIGREF:SYNCS": _syncs_section(),
    }


app = typer.Typer(add_completion=False)


@app.command()
def main(
    *,
    check: Annotated[
        bool,
        typer.Option(
            "--check",
            help="Check that docs are up to date (exit non-zero if not)",
        ),
    ] = False,
) -> None:
    """Generate or check config reference tables in config-reference.md."""
    sections = _generate_sections()
    current = (
        CONFIG_REFERENCE_MD.read_text(encoding="utf-8")
        if CONFIG_REFERENCE_MD.exists()
        else ""
    )
    expected = current
    for name, body in sections.items():
        expected = splice_section(expected, name, body)

    if check:
        if current == expected:
            _stdout.print(
                "Config reference in config-reference.md is up to date.",
                markup=False,
            )
        else:
            _stderr.print(
                f"Config reference in {CONFIG_REFERENCE_MD} is out of date.\n"
                "Run `mise run configdocs` to regenerate.",
                markup=False,
            )
            sys.exit(1)
    else:
        CONFIG_REFERENCE_MD.write_text(expected, encoding="utf-8")
        _stdout.print(
            f"Updated config reference in {CONFIG_REFERENCE_MD}",
            markup=False,
        )


if __name__ == "__main__":
    app()
