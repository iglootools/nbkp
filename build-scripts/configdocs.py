"""
Auto-generate configuration reference tables into docs/config-reference.md.

Introspects the config protocol models and splices field tables into
docs/config-reference.md between marker comments. Use --check to verify the
docs are up to date.

Usage:
    python build-scripts/configdocs.py          # regenerate the tables in the doc
    python build-scripts/configdocs.py --check  # exit non-zero if out of date

Why hand-rolled instead of a library?
    Existing Pydantic doc-gen tools (docdantic, mdantic, settings-doc,
    pydantic-settings-export) are MkDocs/Sphinx plugins designed to run inside
    a documentation build pipeline. They can't be invoked as a standalone
    function to produce a .md file with a --check mode. Our requirements
    (kebab-case aliases, hidden fields, discriminator overrides, interleaved
    prose sections) are too specific for any of them. The introspection code
    is ~120 lines and unlikely to need changes unless the model structure
    fundamentally changes.
"""

import sys
from pathlib import Path
from types import UnionType
from typing import Annotated, Literal, TypeIs, get_args, get_origin

import typer
from pydantic import BaseModel
from pydantic.fields import FieldInfo
from rich.console import Console

from nbkp.config.protocol.ssh_endpoint import SshConnectionOptions, SshEndpoint
from nbkp.config.protocol.sync import RsyncOptions, SyncConfig
from nbkp.config.protocol.sync_endpoint import BtrfsSnapshotConfig, SyncEndpoint
from nbkp.config.protocol.volume import (
    LocalVolume,
    LuksEncryptionConfig,
    MountConfig,
    RemoteVolume,
)

CONFIG_REFERENCE_MD = Path("docs/config-reference.md")

_stdout = Console(soft_wrap=True, highlight=False)
_stderr = Console(stderr=True, soft_wrap=True, highlight=False)


def _begin_marker(name: str) -> str:
    return (
        f"<!-- BEGIN {name} (auto-generated by: mise run configdocs"
        " — do not edit manually) -->"
    )


def _end_marker(name: str) -> str:
    return f"<!-- END {name} -->"


def _marker_problem(file_content: str, begin: str, end: str) -> str | None:
    """Say what is wrong with a section's markers, or None when they are usable."""
    if begin not in file_content or end not in file_content:
        return "not found"
    if file_content.count(begin) > 1 or file_content.count(end) > 1:
        return "repeated"
    if file_content.find(end) < file_content.find(begin):
        return "out of order (END before BEGIN)"
    return None


def splice_section(file_content: str, name: str, body: str) -> str:
    """
    Replace content between BEGIN/END markers for the given section name.

    Exits when either marker is missing or repeated, or END comes before BEGIN:
    splicing would then rewrite the wrong span of the file without a word.
    """
    begin = _begin_marker(name)
    end = _end_marker(name)
    problem = _marker_problem(file_content, begin, end)
    if problem is not None:
        _stderr.print(
            f"Error: markers for {name} {problem} in {CONFIG_REFERENCE_MD}.\n"
            f"Expected, once each and in this order:\n  {begin}\n  {end}",
            markup=False,
        )
        sys.exit(1)
    begin_idx = file_content.find(begin)
    end_idx = file_content.find(end)
    return (
        file_content[:begin_idx]
        + begin
        + "\n"
        + body
        + end
        + file_content[end_idx + len(end) :]
    )


